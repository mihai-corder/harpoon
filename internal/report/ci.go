package report

import (
	"encoding/json"
	"html/template"
	"os"
	"strings"
	"time"

	"github.com/mihai-corder/harpoon/internal/runner"
)

// CIReport is the machine-readable summary of one harpoon run, shared by
// the JSON report consumed by CI automation and the rendered HTML page.
type CIReport struct {
	Collection string     `json:"collection"`
	StartedAt  time.Time  `json:"started_at"`
	DurationMS float64    `json:"duration_ms"`
	Passed     int        `json:"passed"`
	Failed     int        `json:"failed"`
	Results    []CIResult `json:"results"`
}

type CIResult struct {
	Name       string    `json:"name"`
	Method     string    `json:"method"`
	URL        string    `json:"url"`
	Status     int       `json:"status"`
	DurationMS float64   `json:"duration_ms"`
	Err        string    `json:"err,omitempty"`
	Failures   []string  `json:"failures,omitempty"`
	Checks     []CICheck `json:"checks,omitempty"`
}

type CICheck struct {
	Kind   string `json:"kind"`
	OK     bool   `json:"ok"`
	Detail string `json:"detail"`
}

func (r CIReport) Total() int { return r.Passed + r.Failed }

// BuildCIReport summarizes a run. started is when the run began, so the
// reported duration is wall time, not just the sum of request durations.
func BuildCIReport(collection string, started time.Time, results []runner.Result) CIReport {
	rep := CIReport{
		Collection: collection,
		StartedAt:  started,
		DurationMS: float64(time.Since(started).Microseconds()) / 1000,
		Results:    make([]CIResult, 0, len(results)),
	}

	for _, r := range results {
		if r.Passed() {
			rep.Passed++
		} else {
			rep.Failed++
		}

		out := CIResult{
			Name:       r.Name,
			Method:     r.Method,
			URL:        r.URL,
			Status:     r.Status,
			DurationMS: ms(r.Duration),
			Failures:   r.Failures,
		}
		if r.Err != nil {
			out.Err = r.Err.Error()
		}
		for _, c := range r.Checks {
			out.Checks = append(out.Checks, CICheck{Kind: c.Kind, OK: c.OK, Detail: c.Detail})
		}
		rep.Results = append(rep.Results, out)
	}
	return rep
}

// WriteJSON writes the report as indented JSON.
func (r CIReport) WriteJSON(path string) error {
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(data, '\n'), 0o644)
}

// WriteHTML renders a self-contained dark-themed report page.
func (r CIReport) WriteHTML(path string) error {
	return os.WriteFile(path, []byte(r.HTML()), 0o644)
}

func (r CIReport) HTML() string {
	var sb strings.Builder
	tmpl := template.Must(template.New("report").Parse(htmlTemplate))
	if err := tmpl.Execute(&sb, r); err != nil {
		return "<!-- template error: " + template.HTMLEscapeString(err.Error()) + " -->"
	}
	return sb.String()
}

func ms(d time.Duration) float64 {
	return float64(d.Microseconds()) / 1000
}

